def table(slide, l, t, w, h, data, widths=None, fs=10, hfs=10, header=True):
    rows, cols = len(data), len(data[0])
    shp = slide.shapes.add_table(rows, cols, Inches(l), Inches(t), Inches(w), Inches(h))
    tbl = shp.table
    tbl.first_row = header
    if widths:
        tot = sum(widths)
        for i, cw in enumerate(widths):
            tbl.columns[i].width = Emu(int(Inches(w) * cw / tot))
    for ri, row in enumerate(data):
        tbl.rows[ri].height = Inches(max(0.24, h / rows - 0.02))
        for ci, val in enumerate(row):
            cell = tbl.cell(ri, ci)
            cell.margin_left = cell.margin_right = Pt(5)
            cell.margin_top = cell.margin_bottom = Pt(2)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.fill.solid()
            cell.fill.fore_color.rgb = rgb(INK if (header and ri == 0) else
                                           (PAPER2 if ri % 2 == 0 else "FFFFFF"))
            tf = cell.text_frame; tf.word_wrap = True
            p = tf.paragraphs[0]
            r = p.add_run(); r.text = str(val)
            r.font.name = HEI
            r.font.size = Pt(hfs if (header and ri == 0) else fs)
            r.font.bold = header and ri == 0
            r.font.color.rgb = rgb("FFFFFF" if (header and ri == 0) else INK2)
    return tbl


def timeline(slide, l, t, w, nodes, hi_idx):
    """nodes: list of (year, label)"""
    n = len(nodes)
    slot = w / n
    rect(slide, l + 0.1, t + 0.40, w - 0.2, 0.018, fill=LINE)
    for i, (yr, lab) in enumerate(nodes):
        cx = l + slot * (i + 0.5)
        hi = (i == hi_idx)
        rect(slide, cx - 0.075, t + 0.33, 0.15, 0.15,
             fill=RED if hi else GOLD, line=PAPER, lw=2, shape=MSO_SHAPE.OVAL)
        text(slide, cx - slot / 2, t + 0.02, slot, 0.26,
             [{"text": yr, "size": 11, "bold": True, "color": RED if hi else GOLD,
               "align": PP_ALIGN.CENTER}])
        text(slide, cx - slot / 2, t + 0.56, slot, 0.6,
             [{"text": lab, "size": 9.5, "bold": hi, "color": RED if hi else INK2,
               "align": PP_ALIGN.CENTER, "line": 1.15}])


def banner(slide, l, t, w, h, body, size=13):
    rect(slide, l, t, w, h, fill=INK)
    text(slide, l + 0.24, t + 0.10, w - 0.48, h - 0.20,
         [{"text": body, "size": size, "color": "FFFFFF", "line": 1.35}],
         anchor=MSO_ANCHOR.MIDDLE)


def filmstrip(slide, names, l, t, w, h, captions=None, cap_h=0.24):
    """一排整页缩略图（页速览条）。"""
    n = len(names); gap = 0.11
    cw = (w - (n - 1) * gap) / n
    bh = h - cap_h
    for i, nm in enumerate(names):
        cl = l + i * (cw + gap)
        path = os.path.join(CROPS, nm + ".png")
        iw, ih = Image.open(path).size
        r = min(cw / iw, bh / ih)
        dw, dh = iw * r, ih * r
        dl, dt = cl + (cw - dw) / 2, t + (bh - dh) / 2
        slide.shapes.add_picture(path, Inches(dl), Inches(dt), Inches(dw), Inches(dh))
        rect(slide, dl, dt, dw, dh, fill=None, line="C9C2B2", lw=0.75)
        if captions:
            text(slide, cl, t + bh + 0.01, cw, cap_h,
                 [{"text": captions[i], "size": 9, "color": MUTE, "align": PP_ALIGN.CENTER}])


