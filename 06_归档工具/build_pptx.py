# ---------------------------------------------------------------- 基础工具
def rgb(h):
    return RGBColor.from_string(h)


def rect(slide, l, t, w, h, fill=None, line=None, lw=0.75, shape=MSO_SHAPE.RECTANGLE):
    s = slide.shapes.add_shape(shape, Inches(l), Inches(t), Inches(w), Inches(h))
    if fill:
        s.fill.solid(); s.fill.fore_color.rgb = rgb(fill)
    else:
        s.fill.background()
    if line:
        s.line.color.rgb = rgb(line); s.line.width = Pt(lw)
    else:
        s.line.fill.background()
    s.shadow.inherit = False
    return s


def text(slide, l, t, w, h, blocks, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP):
    """blocks: list of dict(text,size,bold,color,font,space_after,line,align)"""
    tb = slide.shapes.add_textbox(Inches(l), Inches(t), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = Pt(2)
    tf.margin_top = tf.margin_bottom = Pt(0)
    tf.vertical_anchor = anchor
    for i, b in enumerate(blocks):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = b.get("align", align)
        p.space_after = Pt(b.get("space_after", 4))
        p.space_before = Pt(b.get("space_before", 0))
        if b.get("line"):
            p.line_spacing = b["line"]
        r = p.add_run(); r.text = b["text"]
        f = r.font
        f.name = b.get("font", HEI)
        f.size = Pt(b.get("size", 12))
        f.bold = b.get("bold", False)
        f.color.rgb = rgb(b.get("color", INK2))
    return tb


